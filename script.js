    nextBtn.style.display = currentImages.length > 1 ? 'flex' : 'none';
    
    prevBtn.onclick = function(e) {
      e.stopPropagation();
      goToPrev();
    };
    nextBtn.onclick = function(e) {
      e.stopPropagation();
      goToNext();
    };
